create or replace function public.event_profitability(p_party_id bigint)
returns table(event_id bigint, gross_revenue integer, discounts integer, refunds integer,
  platform_fee integer, net_platform_gain integer, host_earnings integer, paid_tickets bigint)
language sql security definer set search_path = public as $$
  select p.id,
    coalesce(sum(case when o.payment_status='confirmed' then o.total + coalesce(o.promo_discount,0) else 0 end),0)::integer,
    coalesce(sum(case when o.payment_status='confirmed' then coalesce(o.promo_discount,0) else 0 end),0)::integer,
    coalesce(sum(coalesce(o.refund_amount,0)),0)::integer,
    round(coalesce(sum(case when o.payment_status='confirmed' then o.total else 0 end),0) * 0.15)::integer,
    round(coalesce(sum(case when o.payment_status='confirmed' then o.total else 0 end),0) * 0.15)::integer,
    (coalesce(sum(case when o.payment_status='confirmed' then o.total else 0 end),0) - round(coalesce(sum(case when o.payment_status='confirmed' then o.total else 0 end),0) * 0.15))::integer,
    coalesce(sum(case when o.payment_status='confirmed' then o.quantity else 0 end),0)::bigint
  from public.parties p left join public.orders o on o.party_id=p.id
  where p.id=p_party_id
    and (public.user_has_permission((select auth.uid()), 'analytics.revenue')
      or public.user_has_permission((select auth.uid()), 'revenue.view'))
  group by p.id;
$$;
revoke all on function public.event_profitability(bigint) from public, anon;
grant execute on function public.event_profitability(bigint) to authenticated, service_role;

-- Complimentary tickets are real confirmed orders with total 0, so they have
-- QR codes and appear in attendee lists, but never enter paid revenue.
create or replace function public.issue_complimentary_ticket(
  p_party_id bigint, p_ticket_type_id bigint, p_quantity integer,
  p_email text, p_guest_name text default null, p_user_id uuid default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_party public.parties; v_type public.ticket_types; v_ref text; v_order public.orders;
begin
  if not public.user_has_permission((select auth.uid()), 'tickets.complimentary') then raise exception 'Forbidden' using errcode='42501'; end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 20 or p_email is null or p_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then raise exception 'Valid email and quantity 1–20 are required'; end if;
  select * into v_party from public.parties where id=p_party_id for update;
  if not found or v_party.status <> 'approved' or v_party.cancelled_at is not null then raise exception 'Event is not available'; end if;
  select * into v_type from public.ticket_types where id=p_ticket_type_id and party_id=p_party_id for update;
  if not found or not v_type.active or v_type.quantity-v_type.sold < p_quantity then raise exception 'Not enough tickets left on this tier'; end if;
  v_ref := 'COMP-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,12));
  insert into public.orders(user_id, customer_email, guest_name, ticket_access_token, ticket_access_expires_at, party_id, ticket_type_id, tier, quantity, unit_price, service_fee, total, order_ref, payment_ref, status, payment_status)
    values(p_user_id, lower(trim(p_email)), nullif(trim(p_guest_name),''), case when p_user_id is null then encode(gen_random_bytes(32),'hex') else null end,
      case when p_user_id is null then now() + interval '5 years' else null end, p_party_id, p_ticket_type_id, 'complimentary', p_quantity, 0, 0, 0, v_ref, v_ref, 'pending', 'pending') returning * into v_order;
  perform public.confirm_order_payment(v_order.id);
  select * into v_order from public.orders where id=v_order.id;
  perform public.write_audit_log('complimentary_ticket_issued', 'order', v_order.id::text,
    jsonb_build_object('party_id',p_party_id,'email',p_email,'quantity',p_quantity,'order_ref',v_order.order_ref));
  return jsonb_build_object('order_id',v_order.id,'order_ref',v_order.order_ref,'ticket_access_token',v_order.ticket_access_token,'email',v_order.customer_email);
end;
$$;
revoke all on function public.issue_complimentary_ticket(bigint,bigint,integer,text,text,uuid) from public, anon;
grant execute on function public.issue_complimentary_ticket(bigint,bigint,integer,text,text,uuid) to authenticated, service_role;

