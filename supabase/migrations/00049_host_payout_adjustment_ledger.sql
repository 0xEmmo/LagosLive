create or replace function public.host_payout_balance()
returns table(
  sales_revenue integer,
  platform_fee integer,
  sales_earnings integer,
  ledger_adjustments integer,
  available integer
)
language sql
security definer set search_path = public
as $$
  with sales as (
    select coalesce(sum(o.total),0)::integer as gross
      from public.orders o
      join public.parties p on p.id=o.party_id
     where p.created_by=(select auth.uid())
       and o.payment_status='confirmed'
       and coalesce(o.refund_status,'none') in ('none','rejected')
       and o.total>0
       and not exists(select 1 from public.payout_items pi where pi.order_id=o.id and not pi.released)
  ), adjustments as (
    select coalesce(sum(a.amount),0)::integer as amount
      from public.host_payout_adjustments a
     where a.host_user_id=(select auth.uid())
       and not exists(select 1 from public.payout_adjustment_items pai where pai.adjustment_id=a.id and not pai.released)
  )
  select sales.gross,
         round(sales.gross*0.15)::integer,
         (sales.gross-round(sales.gross*0.15))::integer,
         adjustments.amount,
         greatest(0,(sales.gross-round(sales.gross*0.15))+adjustments.amount)::integer
    from sales cross join adjustments;
$$;
revoke all on function public.host_payout_balance() from public, anon;
grant execute on function public.host_payout_balance() to authenticated;

