create or replace function public.admin_host_payout_ledger(p_host_user_id uuid)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  v_sales integer;
  v_fee integer;
  v_adjustments integer;
  v_available integer;
  v_ledger jsonb;
begin
  if not public.user_has_permission((select auth.uid()),'payouts.adjust_host') then
    raise exception 'Forbidden' using errcode='42501';
  end if;
  if p_host_user_id is null then raise exception 'Host account is required' using errcode='22023'; end if;
  select coalesce(sum(o.total),0)::integer into v_sales
    from public.orders o join public.parties p on p.id=o.party_id
   where p.created_by=p_host_user_id and o.payment_status='confirmed'
     and coalesce(o.refund_status,'none') in ('none','rejected') and o.total>0
     and not exists(select 1 from public.payout_items pi where pi.order_id=o.id and not pi.released);
  v_fee := round(v_sales*0.15)::integer;
  select coalesce(sum(a.amount),0)::integer into v_adjustments
    from public.host_payout_adjustments a
   where a.host_user_id=p_host_user_id
     and not exists(select 1 from public.payout_adjustment_items pai where pai.adjustment_id=a.id and not pai.released);
  v_available := greatest(0,v_sales-v_fee+v_adjustments);
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',a.id,'amount',a.amount,'note',a.note,'reference',a.reference,
    'actor_id',a.actor_id,'created_at',a.created_at
  ) order by a.created_at desc,a.id desc),'[]'::jsonb) into v_ledger
    from public.host_payout_adjustments a where a.host_user_id=p_host_user_id;
  return jsonb_build_object(
    'host_user_id',p_host_user_id,'sales_revenue',v_sales,'platform_fee',v_fee,
    'sales_earnings',v_sales-v_fee,'ledger_adjustments',v_adjustments,
    'available',v_available,'ledger',v_ledger
  );
end;
$$;
revoke all on function public.admin_host_payout_ledger(uuid) from public, anon;
grant execute on function public.admin_host_payout_ledger(uuid) to authenticated;

create or replace function public.admin_adjust_host_payout(
  p_host_user_id uuid,
  p_amount integer,
  p_note text,
  p_reference text default null
)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  v_actor uuid := (select auth.uid());
  v_profile public.profiles%rowtype;
  v_sales integer;
  v_fee integer;
  v_adjustments integer;
  v_available integer;
  v_after integer;
  v_id bigint;
begin
  if not public.user_has_permission(v_actor,'payouts.adjust_host') then
    raise exception 'Forbidden' using errcode='42501';
  end if;
  if p_host_user_id is null or p_amount is null or p_amount=0
     or length(btrim(coalesce(p_note,'')))<3 then
    raise exception 'Host, non-zero amount and an audit note are required' using errcode='22023';
  end if;
  if length(btrim(coalesce(p_note,'')))>500 or length(btrim(coalesce(p_reference,'')))>120 then
    raise exception 'Note or reference is too long' using errcode='22023';
  end if;
  select * into v_profile from public.profiles where id=p_host_user_id for update;
  if not found or v_profile.role not in ('organizer','finance','support','admin','super_admin') then
    raise exception 'Host account not found' using errcode='P0002';
  end if;

  select coalesce(sum(o.total),0)::integer into v_sales
    from public.orders o join public.parties p on p.id=o.party_id
   where p.created_by=p_host_user_id and o.payment_status='confirmed'
     and coalesce(o.refund_status,'none') in ('none','rejected') and o.total>0
     and not exists(select 1 from public.payout_items pi where pi.order_id=o.id and not pi.released);
  v_fee := round(v_sales*0.15)::integer;
  select coalesce(sum(a.amount),0)::integer into v_adjustments
    from public.host_payout_adjustments a
   where a.host_user_id=p_host_user_id
     and not exists(select 1 from public.payout_adjustment_items pai where pai.adjustment_id=a.id and not pai.released);
  v_available := v_sales-v_fee+v_adjustments;
  if p_amount<0 and v_available+p_amount<0 then
    raise exception 'Adjustment would reduce unencumbered payout availability below zero' using errcode='P0001';
  end if;

  insert into public.host_payout_adjustments(host_user_id,amount,note,reference,actor_id)
  values(p_host_user_id,p_amount,btrim(p_note),nullif(btrim(coalesce(p_reference,'')),''),v_actor)
  returning id into v_id;
  v_after := v_available+p_amount;
  perform public.write_audit_log('host_payout_adjusted','user',p_host_user_id::text,
    jsonb_build_object('adjustment_id',v_id,'amount',p_amount,'note',btrim(p_note),
      'reference',p_reference,'available_before',v_available,'available_after',v_after));
  return jsonb_build_object('adjustment_id',v_id,'balance_before',v_available,'balance_after',v_after,
    'host_user_id',p_host_user_id,'amount',p_amount);
end;
$$;
revoke all on function public.admin_adjust_host_payout(uuid,integer,text,text) from public, anon;
grant execute on function public.admin_adjust_host_payout(uuid,integer,text,text) to authenticated;

-- Request payouts from unclaimed net sales plus unclaimed ledger adjustments.
-- The profile row lock serializes this with admin adjustments for that host.
create or replace function public.request_payout()
returns bigint
language plpgsql
security definer set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  v_profile public.profiles%rowtype;
  v_bank public.host_bank_accounts%rowtype;
  v_revenue integer;
  v_fee integer;
  v_adjustment integer;
  v_amount integer;
  v_payout_id bigint;
  v_period_start date;
  v_period_end date;
  v_adjustment_start date;
  v_adjustment_end date;
  v_min constant integer := 1000;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode='42501'; end if;
  select * into v_profile from public.profiles where id=v_uid for update;
  if not found then raise exception 'Profile not found' using errcode='P0002'; end if;
  if v_profile.role not in ('organizer','finance','support','admin','super_admin') then
    raise exception 'Only event hosts can request payouts' using errcode='42501';
  end if;
  if coalesce(v_profile.host_verification_status,'unverified')<>'verified' then
    raise exception 'Verify your host account before requesting payouts' using errcode='42501';
  end if;
  if v_profile.account_status<>'active' then raise exception 'Your account must be active to request payouts' using errcode='42501'; end if;
  if public.has_active_payout_freeze(v_uid) then
    raise exception 'Your payouts are on hold while we review a recent transfer. Our team will be in touch.' using errcode='42501';
  end if;
  select * into v_bank from public.host_bank_accounts
   where user_id=v_uid and removed_at is null order by created_at desc limit 1;
  if not found then raise exception 'Add a verified bank account before requesting payouts' using errcode='23514'; end if;

  select coalesce(sum(o.total),0)::integer,min(o.created_at)::date,max(o.created_at)::date
    into v_revenue,v_period_start,v_period_end
    from public.orders o join public.parties p on p.id=o.party_id
   where p.created_by=v_uid and o.payment_status='confirmed'
     and coalesce(o.refund_status,'none') in ('none','rejected') and o.total>0
     and not exists(select 1 from public.payout_items pi where pi.order_id=o.id and not pi.released);
  select coalesce(sum(a.amount),0)::integer,min(a.created_at)::date,max(a.created_at)::date
    into v_adjustment,v_adjustment_start,v_adjustment_end
    from public.host_payout_adjustments a
   where a.host_user_id=v_uid
     and not exists(select 1 from public.payout_adjustment_items pai where pai.adjustment_id=a.id and not pai.released);
  v_fee := round(v_revenue*0.15)::integer;
  v_amount := v_revenue-v_fee+v_adjustment;
  if v_revenue<v_min and v_amount<v_min then
    raise exception 'Payout amount is below the minimum' using errcode='P0001';
  end if;
  if v_amount<=0 then raise exception 'No positive payout is available after adjustments' using errcode='P0001'; end if;

  insert into public.payouts(organizer_id,bank_account_id,period_start,period_end,revenue,platform_fee,
    adjustment_total,amount,status,bank_last4)
  values(v_uid,v_bank.id,coalesce(v_period_start,v_adjustment_start,current_date),
    coalesce(v_period_end,v_adjustment_end,current_date),v_revenue,v_fee,v_adjustment,v_amount,
    'pending',v_bank.account_number_last4)
  returning id into v_payout_id;

  begin
    insert into public.payout_items(payout_id,order_id,amount)
    select v_payout_id,o.id,o.total from public.orders o
      join public.parties p on p.id=o.party_id
     where p.created_by=v_uid and o.payment_status='confirmed'
       and coalesce(o.refund_status,'none') in ('none','rejected') and o.total>0
       and not exists(select 1 from public.payout_items pi where pi.order_id=o.id and not pi.released);
    insert into public.payout_adjustment_items(payout_id,adjustment_id,amount)
    select v_payout_id,a.id,a.amount from public.host_payout_adjustments a
     where a.host_user_id=v_uid
       and not exists(select 1 from public.payout_adjustment_items pai where pai.adjustment_id=a.id and not pai.released);
  exception when unique_violation then
    raise exception 'A payout for this revenue or adjustment is already being processed' using errcode='23505';
  end;
  perform public.write_audit_log('payout_requested','payout',v_payout_id::text,
    jsonb_build_object('revenue',v_revenue,'platform_fee',v_fee,'adjustment_total',v_adjustment,
      'amount',v_amount,'bank_account_id',v_bank.id,'bank_last4',v_bank.account_number_last4));
  return v_payout_id;
end;
$$;
revoke execute on function public.request_payout() from public, anon;
grant execute on function public.request_payout() to authenticated;

-- Returning a rejected payout releases its adjustment claims so they remain
-- available for a later request; transfers in flight retain their claim.
create or replace function public.release_rejected_payout_adjustments()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.status='rejected' and old.status is distinct from new.status then
    update public.payout_adjustment_items set released=true
     where payout_id=new.id and not released;
  end if;
  return new;
end;
$$;
drop trigger if exists payout_adjustment_claim_release on public.payouts;
create trigger payout_adjustment_claim_release
after update of status on public.payouts
for each row execute function public.release_rejected_payout_adjustments();

-- Existing customer wallet adjustments remain a separate ledger. Enforce that
-- explicit credit/debit kinds agree with the sign chosen by the administrator.
create or replace function public.adjust_wallet(
  p_user_id uuid,
  p_amount integer,
  p_kind text,
  p_note text,
  p_reference text default null
)
returns public.wallets
language plpgsql security definer set search_path = public as $$
declare
  v_wallet public.wallets%rowtype;
  v_actor uuid := (select auth.uid());
begin
  if not public.user_has_permission(v_actor,'wallets.adjust') then raise exception 'Forbidden' using errcode='42501'; end if;
  if p_user_id is null or p_amount is null or p_amount=0 or btrim(coalesce(p_note,''))='' then
    raise exception 'A user, non-zero amount and note are required' using errcode='22023';
  end if;
  if p_kind not in ('admin_credit','admin_debit','offline_credit','deal_adjustment') then
    raise exception 'Invalid wallet adjustment type' using errcode='22023';
  end if;
  if (p_kind in ('admin_credit','offline_credit') and p_amount<0)
     or (p_kind='admin_debit' and p_amount>0) then
    raise exception 'The amount sign does not match the wallet adjustment type' using errcode='22023';
  end if;
  insert into public.wallets(user_id) values(p_user_id) on conflict do nothing;
  select * into v_wallet from public.wallets where user_id=p_user_id for update;
  if v_wallet.balance+p_amount<0 then raise exception 'Wallet balance cannot become negative' using errcode='P0001'; end if;
  update public.wallets set balance=balance+p_amount,updated_at=now()
   where user_id=p_user_id returning * into v_wallet;
  insert into public.wallet_ledger(user_id,amount,balance_after,kind,note,reference,actor_id)
    values(p_user_id,p_amount,v_wallet.balance,p_kind,btrim(p_note),nullif(btrim(coalesce(p_reference,'')),''),v_actor);
  perform public.write_audit_log('wallet_adjusted','user',p_user_id::text,
    jsonb_build_object('amount',p_amount,'kind',p_kind,'note',p_note,'reference',p_reference,'balance_after',v_wallet.balance));
  return v_wallet;
end;
$$;

-- The order financial trigger also protects the new wallet tender column from
-- direct client updates. Server-side service-role payment RPCs remain allowed.
create or replace function public.guard_order_financial_columns()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if auth.role() not in ('anon','authenticated') then return new; end if;
  if new.party_id is distinct from old.party_id
     or new.tier is distinct from old.tier
     or new.ticket_type_id is distinct from old.ticket_type_id
     or new.quantity is distinct from old.quantity
     or new.unit_price is distinct from old.unit_price
     or new.service_fee is distinct from old.service_fee
     or new.total is distinct from old.total
     or new.status is distinct from old.status
     or new.payment_status is distinct from old.payment_status
     or new.payment_ref is distinct from old.payment_ref
     or new.order_ref is distinct from old.order_ref
     or new.payment_method is distinct from old.payment_method
     or new.wallet_paid is distinct from old.wallet_paid
     or new.refund_status is distinct from old.refund_status
     or new.refund_amount is distinct from old.refund_amount
     or new.user_id is distinct from old.user_id
     or new.customer_email is distinct from old.customer_email
     or new.ticket_access_token is distinct from old.ticket_access_token
  then
    raise exception 'Order amounts, payment state and buyer identity are server-authoritative. Use the audited payment RPCs.' using errcode='42501';
  end if;
  return new;
end;
$$;
