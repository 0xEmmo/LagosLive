-- ==========================================================================
-- 00049 - Separate host payout adjustment ledger
-- These entries change withdrawable payout availability only. They never
-- rewrite ticket orders, event sales, discounts, or platform revenue.
-- ==========================================================================

alter table public.payouts
  add column if not exists adjustment_total integer not null default 0;

-- The original payout guard predates adjustment_total; keep the new figure just
-- as server-authoritative as sales, fee and amount.
create or replace function public.guard_payout_money_columns()
returns trigger
language plpgsql
security invoker set search_path = public
as $$
begin
  if current_user not in ('anon', 'authenticated') then return new; end if;
  if new.organizer_id is distinct from old.organizer_id
     or new.bank_account_id is distinct from old.bank_account_id
     or new.revenue is distinct from old.revenue
     or new.platform_fee is distinct from old.platform_fee
     or new.adjustment_total is distinct from old.adjustment_total
     or new.amount is distinct from old.amount
     or new.period_start is distinct from old.period_start
     or new.period_end is distinct from old.period_end
     or new.bank_last4 is distinct from old.bank_last4
     or new.paid_at is distinct from old.paid_at
     or new.created_at is distinct from old.created_at
     or new.transfer_code is distinct from old.transfer_code
     or new.transfer_reference is distinct from old.transfer_reference
     or new.reversed_at is distinct from old.reversed_at
     or new.reversal_code is distinct from old.reversal_code
     or new.reversal_reference is distinct from old.reversal_reference
     or new.reversal_reason is distinct from old.reversal_reason
     or new.transfer_attempted_at is distinct from old.transfer_attempted_at
  then
    raise exception 'Payout amounts, period and beneficiary are computed by the server and cannot be edited.' using errcode='42501';
  end if;
  return new;
end;
$$;

create table if not exists public.host_payout_adjustments (
  id bigint generated by default as identity primary key,
  host_user_id uuid not null references public.profiles(id) on delete restrict,
  amount integer not null check (amount <> 0),
  note text not null check (length(btrim(note)) > 0),
  reference text,
  actor_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists host_payout_adjustments_host_idx
  on public.host_payout_adjustments(host_user_id, created_at desc);
alter table public.host_payout_adjustments enable row level security;
revoke all on public.host_payout_adjustments from public, anon, authenticated;

-- Adjustments are claimed by exactly one live payout. Rejected payouts release
-- these claims in a trigger below, just like the existing payout_items ledger.
create table if not exists public.payout_adjustment_items (
  id bigint generated by default as identity primary key,
  payout_id bigint not null references public.payouts(id) on delete cascade,
  adjustment_id bigint not null references public.host_payout_adjustments(id) on delete restrict,
  amount integer not null check (amount <> 0),
  released boolean not null default false,
  created_at timestamptz not null default now(),
  unique (payout_id, adjustment_id)
);
create unique index if not exists payout_adjustment_items_one_active_claim_idx
  on public.payout_adjustment_items(adjustment_id) where not released;
create index if not exists payout_adjustment_items_payout_idx
  on public.payout_adjustment_items(payout_id, released);
alter table public.payout_adjustment_items enable row level security;
revoke all on public.payout_adjustment_items from public, anon, authenticated;

