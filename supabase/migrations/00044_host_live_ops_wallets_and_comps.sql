-- ==========================================================================
-- Lagos Live live operations: host coupons, wallets, event profitability and
-- complimentary tickets. All money-moving or ticket-issuing actions are
-- server-side, permission checked and audit logged.
-- ========================================================================

-- Event-scoped coupons. Existing global promos remain valid with party_id NULL.
alter table public.promos add column if not exists party_id bigint references public.parties(id) on delete cascade;
alter table public.promos add column if not exists created_by uuid references auth.users(id) on delete set null;
create index if not exists promos_party_idx on public.promos(party_id, active);

-- Wallets are integer naira balances. The ledger is append-only; the balance is
-- updated only by the guarded RPC below.
create table if not exists public.wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance integer not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.wallet_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount integer not null check (amount <> 0),
  balance_after integer not null check (balance_after >= 0),
  kind text not null check (kind in ('admin_credit','admin_debit','offline_credit','deal_adjustment','gift_ticket_reserve','gift_ticket_release')),
  note text not null,
  reference text,
  actor_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists wallet_ledger_user_idx on public.wallet_ledger(user_id, created_at desc);
alter table public.wallets enable row level security;
alter table public.wallet_ledger enable row level security;
drop policy if exists "users read own wallet" on public.wallets;
create policy "users read own wallet" on public.wallets for select using (user_id = (select auth.uid()));
drop policy if exists "users read own wallet ledger" on public.wallet_ledger;
create policy "users read own wallet ledger" on public.wallet_ledger for select using (user_id = (select auth.uid()));

create or replace function public.adjust_wallet(
  p_user_id uuid,
  p_amount integer,
  p_kind text,
  p_note text,
  p_reference text default null
) returns public.wallets
language plpgsql security definer set search_path = public as $$
declare
  v_wallet public.wallets;
  v_kind text := p_kind;
begin
  if not public.user_has_permission((select auth.uid()), 'wallets.adjust') then
    raise exception 'Forbidden' using errcode = '42501';
  end if;
  if p_user_id is null or p_amount = 0 or coalesce(trim(p_note), '') = '' then
    raise exception 'A user, non-zero amount and note are required' using errcode = '22023';
  end if;
  if v_kind not in ('admin_credit','admin_debit','offline_credit','deal_adjustment') then
    raise exception 'Invalid wallet adjustment type' using errcode = '22023';
  end if;
  insert into public.wallets(user_id) values (p_user_id) on conflict do nothing;
  select * into v_wallet from public.wallets where user_id = p_user_id for update;
  if v_wallet.balance + p_amount < 0 then
    raise exception 'Wallet balance cannot become negative' using errcode = 'P0001';
  end if;
  update public.wallets set balance = balance + p_amount, updated_at = now()
    where user_id = p_user_id returning * into v_wallet;
  insert into public.wallet_ledger(user_id, amount, balance_after, kind, note, reference, actor_id)
    values (p_user_id, p_amount, v_wallet.balance, v_kind, trim(p_note), nullif(trim(p_reference), ''), (select auth.uid()));
  perform public.write_audit_log('wallet_adjusted', 'user', p_user_id::text,
    jsonb_build_object('amount', p_amount, 'kind', v_kind, 'note', p_note, 'reference', p_reference,
      'balance_after', v_wallet.balance));
  return v_wallet;
end;
$$;

create or replace function public.create_host_promo(
  p_party_id bigint, p_code text, p_discount_percent integer,
  p_description text default null, p_max_uses integer default null,
  p_starts_at timestamptz default null, p_ends_at timestamptz default null
) returns uuid
language plpgsql security definer set search_path = public as $$
declare v_id uuid; v_owner uuid;
begin
  select created_by into v_owner from public.parties where id = p_party_id;
  if v_owner is null or v_owner <> (select auth.uid()) then raise exception 'Only the event host can create this coupon' using errcode = '42501'; end if;
  if p_code is null or upper(trim(p_code)) !~ '^[A-Z0-9][A-Z0-9_-]{2,23}$' then raise exception 'Invalid coupon code'; end if;
  if p_discount_percent < 1 or p_discount_percent > 100 then raise exception 'Discount must be between 1 and 100 percent'; end if;
  if p_max_uses is not null and p_max_uses < 1 then raise exception 'Maximum uses must be at least 1'; end if;
  if p_starts_at is not null and p_ends_at is not null and p_starts_at > p_ends_at then raise exception 'Start time must be before end time'; end if;
  insert into public.promos(party_id, created_by, code, discount_percent, description, max_uses, starts_at, ends_at)
    values(p_party_id, (select auth.uid()), upper(trim(p_code)), p_discount_percent, nullif(trim(coalesce(p_description,'')),''), p_max_uses, p_starts_at, p_ends_at)
    returning id into v_id;
  perform public.write_audit_log('host_promo_created', 'event', p_party_id::text,
    jsonb_build_object('promo_id', v_id, 'code', upper(trim(p_code)), 'discount_percent', p_discount_percent));
  return v_id;
end;
$$;

